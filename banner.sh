typewrite() {
  local text="$1"
  local delay="${2:-0.03}"   # second arg = delay per char, default 0.03
  local i
  for (( i=0; i<${#text}; i++ )); do
    printf "%s" "${text:$i:1}"
    sleep "$delay"
  done
  printf "\n"
}
